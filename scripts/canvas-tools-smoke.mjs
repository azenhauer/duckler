import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const baseURL = process.env.DUCKLER_PREVIEW_URL || 'http://localhost:5176';
const sharedURL = '/@fs/' + fileURLToPath(new URL('../packages/shared/src/index.ts', import.meta.url)).replaceAll('\\', '/');
await mkdir(new URL('../.tmp/ui-checks/', import.meta.url), { recursive: true });
const browser = await chromium.launch({ headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(baseURL);
  await page.waitForFunction(() => document.querySelector('main')?.getAttribute('aria-busy') === 'false');
  await page.evaluate(async sharedModule => {
    const { cardDb } = await import('/src/lib/cardDb.ts');
    const { createCardFromInput, createCollectionFromInput } = await import(sharedModule);
    const image = document.createElement('canvas'); image.width = 240; image.height = 160;
    const painter = image.getContext('2d'); painter.fillStyle = '#63868d'; painter.fillRect(0, 0, 240, 160);
    await cardDb.cards.bulkPut([
      createCardFromInput({ id: 'image', type: 'image', title: 'Sketch', dataUrl: image.toDataURL('image/png') }),
      createCardFromInput({ id: 'note', type: 'text', title: 'Thought', note: 'Original note' }),
    ]);
    await cardDb.collections.put(createCollectionFromInput({ id: 'tools', name: 'Tools board', cardIds: ['image', 'note'] }));
  }, sharedURL);
  await page.reload();
  await page.getByRole('button', { name: 'Open canvas', exact: true }).click();
  await page.getByRole('button', { name: 'Open canvas Tools board', exact: true }).click();
  const board = page.getByRole('region', { name: 'Canvas Tools board', exact: true });
  const tools = page.getByRole('toolbar', { name: 'Canvas tools' });
  const surface = page.locator('.canvas-surface');
  await expect(page.locator('.react-flow__node-card')).toHaveCount(2);
  const read = () => page.evaluate(async () => {
    const { cardDb } = await import('/src/lib/cardDb.ts');
    return { placements: await cardDb.canvasPlacements.where('canvasId').equals('tools').toArray(),
      elements: await cardDb.canvasElements.where('canvasId').equals('tools').toArray(), connectors: await cardDb.canvasConnectors.where('canvasId').equals('tools').toArray(), cards: await cardDb.cards.toArray() };
  });
  const original = await read();
  const imageId = original.placements.find(item => item.cardId === 'image').id;
  const noteId = original.placements.find(item => item.cardId === 'note').id;
  const imageNode = page.locator(`.react-flow__node[data-id="${imageId}"]`);
  const noteNode = page.locator(`.react-flow__node[data-id="${noteId}"]`);
  const draw = async (tool, offset = 0) => {
    await tools.getByRole('button', { name: tool, exact: true }).click();
    await surface.scrollIntoViewIfNeeded();
    const bounds = await surface.boundingBox();
    await page.mouse.move(bounds.x + 50 + offset, bounds.y + bounds.height * .7);
    await page.mouse.down();
    await page.mouse.move(bounds.x + 180 + offset, bounds.y + bounds.height * .85, { steps: 16 });
    await page.mouse.up();
  };
  for (const [index, name] of ['Pen', 'Highlighter', 'Rectangle', 'Ellipse'].entries()) {
    await draw(name, index * 150);
    await expect.poll(async () => (await read()).elements.length).toBe(index + 1);
  }
  assert.equal((await read()).elements.find(item => item.style.opacity === .3).kind, 'stroke');
  await tools.getByRole('button', { name: 'Text', exact: true }).click();
  await surface.scrollIntoViewIfNeeded();
  let bounds = await surface.boundingBox();
  await page.mouse.click(bounds.x + bounds.width * .85, bounds.y + bounds.height * .1);
  const textDialog = page.getByRole('dialog', { name: 'Canvas text' });
  await textDialog.getByRole('textbox', { name: 'Annotation text' }).fill('Board annotation <script> is plain text');
  await textDialog.getByRole('button', { name: 'Save text' }).click();
  await expect(textDialog).toHaveCount(0);
  await expect.poll(async () => (await read()).elements.length).toBe(5);
  await tools.getByRole('button', { name: 'Select', exact: true }).click();
  await tools.getByRole('button', { name: 'Fit board', exact: true }).click();
  await imageNode.click({ position: { x: 30, y: 30 } });
  await board.getByRole('button', { name: 'Draw on selected card', exact: true }).click();
  await tools.getByRole('button', { name: 'Rectangle', exact: true }).click();
  await surface.scrollIntoViewIfNeeded();
  const imageBounds = await imageNode.boundingBox();
  await page.mouse.move(imageBounds.x + 30, imageBounds.y + 30); await page.mouse.down();
  await page.mouse.move(imageBounds.x + imageBounds.width * .7, imageBounds.y + imageBounds.height * .6, { steps: 8 }); await page.mouse.up();
  await expect.poll(async () => (await read()).elements.filter(item => item.anchorPlacementId === imageId).length).toBe(1);
  const annotation = (await read()).elements.find(item => item.anchorPlacementId === imageId);
  await board.getByRole('button', { name: 'Rotate +15°', exact: true }).click();
  await expect.poll(async () => (await read()).placements.find(item => item.id === imageId).rotation).toBe(15);
  assert.deepEqual((await read()).elements.find(item => item.id === annotation.id), annotation, 'Anchored geometry stays local when card rotates');
  await tools.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect.poll(async () => (await read()).placements.find(item => item.id === imageId).rotation).toBe(0);
  await tools.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect.poll(async () => (await read()).elements.length).toBe(5);
  await tools.getByRole('button', { name: 'Redo', exact: true }).click();
  await expect.poll(async () => (await read()).elements.length).toBe(6);
  await board.getByRole('button', { name: 'Draw on selected card', exact: true }).click();
  await tools.getByRole('button', { name: 'Select', exact: true }).click();
  await imageNode.click({ position: { x: 15, y: 15 } });
  const handle = imageNode.locator('.react-flow__resize-control.handle.bottom.right');
  await expect(handle).toBeVisible();
  await handle.scrollIntoViewIfNeeded();
  const resizeBounds = await handle.boundingBox();
  await page.mouse.move(resizeBounds.x + resizeBounds.width / 2, resizeBounds.y + resizeBounds.height / 2); await page.mouse.down();
  await page.mouse.move(resizeBounds.x + resizeBounds.width / 2 + 12, resizeBounds.y + resizeBounds.height / 2 + 8, { steps: 10 }); await page.mouse.up();
  await expect.poll(async () => (await read()).placements.find(item => item.id === imageId).width).toBeGreaterThan(210);
  const resized = (await read()).placements.find(item => item.id === imageId);
  assert.ok(Math.abs(resized.width / resized.height - 210 / 194) < .03, 'Image proportions remain locked');
  await tools.getByRole('button', { name: 'Connector', exact: true }).click();
  await surface.scrollIntoViewIfNeeded();
  const source = await imageNode.locator('.react-flow__handle.source').boundingBox();
  const target = await noteNode.locator('.react-flow__handle.target').boundingBox();
  await page.mouse.move(source.x + source.width / 2, source.y + source.height / 2); await page.mouse.down();
  await page.mouse.move(target.x + target.width / 2, target.y + target.height / 2, { steps: 14 }); await page.mouse.up();
  await expect.poll(async () => (await read()).connectors.length).toBe(1);
  assert.deepEqual([(await read()).connectors[0].sourceId, (await read()).connectors[0].targetId], [imageId, noteId]);
  await tools.getByRole('button', { name: 'Select', exact: true }).click();
  await imageNode.getByRole('button', { name: 'Edit Sketch', exact: true }).click();
  const editor = page.getByRole('dialog', { name: 'Card details' });
  await editor.getByRole('textbox', { name: 'Title', exact: true }).fill('Updated Sketch');
  await editor.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(editor).toHaveCount(0);
  await expect(imageNode.getByText('Updated Sketch', { exact: true })).toBeVisible();
  await expect(imageNode.getByText('Review annotations: card changed')).toBeVisible();
  await imageNode.click({ position: { x: 10, y: 10 } });
  await page.keyboard.down('Control');
  await noteNode.click({ position: { x: 10, y: 10 } });
  await page.keyboard.up('Control');
  await expect(imageNode).toHaveClass(/selected/);
  await expect(noteNode).toHaveClass(/selected/);
  const beforeMove = await read();
  await surface.scrollIntoViewIfNeeded();
  const moveBounds = await imageNode.boundingBox();
  await page.mouse.move(moveBounds.x + 20, moveBounds.y + 20); await page.mouse.down();
  await page.mouse.move(moveBounds.x + 70, moveBounds.y + 60, { steps: 10 }); await page.mouse.up();
  await expect.poll(async () => (await read()).placements.find(item => item.id === imageId).x).toBeGreaterThan(beforeMove.placements.find(item => item.id === imageId).x);
  await expect.poll(async () => (await read()).placements.find(item => item.id === noteId).x).toBeGreaterThan(beforeMove.placements.find(item => item.id === noteId).x);
  await tools.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect.poll(async () => (await read()).placements.find(item => item.id === noteId).x).toBe(beforeMove.placements.find(item => item.id === noteId).x);
  await expect.poll(async () => (await read()).placements.find(item => item.id === imageId).x).toBe(beforeMove.placements.find(item => item.id === imageId).x);
  await board.getByRole('button', { name: 'Clear selection', exact: true }).click();
  const picker = page.locator('.canvas-card-picker');
  await picker.getByText('Add cards from library', { exact: true }).click();
  await picker.getByRole('button', { name: 'Add Updated Sketch', exact: true }).click();
  await expect.poll(async () => (await read()).placements.filter(item => item.cardId === 'image').length).toBe(2);
  const duplicate = (await read()).placements.find(item => item.cardId === 'image' && item.id !== imageId);
  assert.equal(duplicate.width, 210, 'Repeated references have independent geometry');
  await page.locator(`.react-flow__node[data-id="${duplicate.id}"]`).getByRole('button', { name: 'Edit Updated Sketch', exact: true }).click();
  await editor.getByRole('textbox', { name: 'Title', exact: true }).fill('Final Sketch');
  await editor.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(editor).toHaveCount(0);
  await expect(page.locator('.canvas-card-node[data-card-id="image"]').getByText('Final Sketch', { exact: true })).toHaveCount(2);
  await picker.getByText('Add cards from library', { exact: true }).click();
  await tools.getByRole('button', { name: 'Fit board', exact: true }).click();
  await imageNode.click({ position: { x: 10, y: 10 } });
  await board.getByRole('button', { name: 'Remove selected', exact: true }).click();
  await expect.poll(async () => (await read()).placements.find(item => item.id === imageId).removed).toBe(true);
  await expect(imageNode).toHaveCount(0);
  assert.equal((await read()).elements.filter(item => item.anchorPlacementId === imageId).length, 1);
  assert.equal((await read()).connectors.length, 1);
  assert.equal((await read()).cards.find(item => item.id === 'image').title, 'Final Sketch');
  const recovery = page.locator('.canvas-recovery');
  await recovery.getByText(/Hidden objects/).click();
  await recovery.getByRole('button', { name: 'Restore placement', exact: true }).click();
  await expect(imageNode).toHaveCount(1);
  await expect.poll(async () => Boolean((await read()).placements.find(item => item.id === imageId).removed)).toBe(false);
  await tools.getByRole('button', { name: 'Eraser', exact: true }).click();
  const rectangle = (await read()).elements.find(item => item.kind === 'rectangle' && !item.anchorPlacementId);
  await page.locator(`.react-flow__node[data-id="${rectangle.id}"]`).click({ position: { x: 4, y: 4 } });
  await expect.poll(async () => (await read()).elements.length).toBe(5);
  await tools.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect.poll(async () => (await read()).elements.length).toBe(6);
  await tools.getByRole('button', { name: 'Select', exact: true }).click();
  await picker.getByText('Add cards from library', { exact: true }).click();
  await tools.getByRole('button', { name: 'Fit board', exact: true }).click();
  await surface.scrollIntoViewIfNeeded();
  const dropPoint = await page.locator('.react-flow').evaluate(element => {
    const rect = element.getBoundingClientRect();
    const matrix = new DOMMatrix(getComputedStyle(element.querySelector('.react-flow__viewport')).transform);
    const x = rect.width * .8, y = rect.height * .9;
    return { x, y, worldX: (x - matrix.e) / matrix.a, worldY: (y - matrix.f) / matrix.d };
  });
  await picker.getByRole('button', { name: 'Add Thought', exact: true }).dragTo(page.locator('.react-flow'), { targetPosition: { x: dropPoint.x, y: dropPoint.y } });
  await expect.poll(async () => (await read()).placements.length).toBe(4);
  const dropped = (await read()).placements.find(item => item.cardId === 'note' && item.id !== noteId);
  assert.ok(Math.abs(dropped.x - dropPoint.worldX) < 2 && Math.abs(dropped.y - dropPoint.worldY) < 2, 'Library drop accounts for pan and zoom');
  const beforeReload = await read();
  await page.screenshot({ path: fileURLToPath(new URL('../.tmp/ui-checks/canvas-tools-desktop.png', import.meta.url)), fullPage: true });
  await page.reload();
  await page.getByRole('button', { name: 'Open canvas', exact: true }).click();
  await page.getByRole('button', { name: 'Open canvas Tools board', exact: true }).click();
  await expect(page.locator('.react-flow__node-card')).toHaveCount(4);
  const afterReload = await read();
  assert.deepEqual(afterReload.placements, beforeReload.placements);
  assert.deepEqual(afterReload.elements, beforeReload.elements);
  assert.deepEqual(afterReload.connectors, beforeReload.connectors);
  await imageNode.click({ position: { x: 10, y: 10 } });
  await board.getByRole('button', { name: 'Rotate +15°', exact: true }).click();
  await expect.poll(async () => (await read()).placements.find(item => item.id === imageId).rotation).toBe(15);
  const otherTab = await page.context().newPage();
  await otherTab.goto(baseURL);
  await otherTab.evaluate(async () => {
    const { readCanvasState, commitCanvasContent } = await import('/src/lib/cardDb.ts');
    const state = await readCanvasState('tools');
    await commitCanvasContent('tools', state.document.revision, { placements: state.placements.map(item => ({ ...item, x: item.x + 500 })), elements: state.elements, connectors: state.connectors });
  });
  const externalX = (await read()).placements.find(item => item.id === imageId).x;
  await tools.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(board.getByRole('alert')).toContainText('Canvas changed elsewhere');
  assert.equal((await read()).placements.find(item => item.id === imageId).x, externalX, 'Stale Undo preserves another tab edit');
  await board.getByRole('button', { name: 'Reload canvas', exact: true }).click();
  await expect(board.getByRole('alert')).toHaveCount(0);
  await expect(tools.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled();
  await otherTab.close();
  await page.setViewportSize({ width: 390, height: 844 });
  await tools.getByRole('button', { name: 'Fit board', exact: true }).click();
  await expect(tools.getByRole('button', { name: 'Text', exact: true })).toBeVisible();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'Mobile tools fit viewport');
  await page.screenshot({ path: fileURLToPath(new URL('../.tmp/ui-checks/canvas-tools-mobile.png', import.meta.url)), fullPage: true });
  assert.deepEqual(errors, []);
  console.log('Canvas drawing, text, anchored annotation, rotation, resize, connectors, card edits, repeated references, recovery, eraser, undo/redo and reload persistence passed.');
} finally { await browser.close(); }
